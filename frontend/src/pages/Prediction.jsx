import React, { useState } from 'react';
import { UserCheck, ShieldAlert, Heart, Play, RefreshCw, CheckCircle2 } from 'lucide-react';
import { predictPatientRisk } from '../services/api';

export default function Prediction() {
  const initialForm = {
    age: 58,
    sex: 1,
    cp: 4, // Asymptomatic
    trestbps: 140,
    chol: 260,
    fbs: 0,
    restecg: 1,
    thalach: 130,
    exang: 1,
    oldpeak: 1.8,
    slope: 2, // Flat
    ca: 1,
    thal: 7 // Reversible defect
  };

  const [formData, setFormData] = useState(initialForm);
  const [loading, setLoading] = useState(false);
  const [result, setResult] = useState(null);
  const [errorMsg, setErrorMsg] = useState('');

  const handleChange = (e) => {
    const { name, value } = e.target;
    setFormData(prev => ({
      ...prev,
      [name]: Number(value)
    }));
  };

  const handlePredict = async (e) => {
    e.preventDefault();
    setLoading(true);
    setErrorMsg('');
    try {
      const res = await predictPatientRisk(formData);
      setResult(res);
    } catch (err) {
      setErrorMsg(err.message || 'Prediction failed.');
    } finally {
      setLoading(false);
    }
  };

  const loadPreset = (type) => {
    if (type === 'high') {
      setFormData({
        age: 64,
        sex: 1,
        cp: 4, // Asymptomatic (classic high risk)
        trestbps: 160,
        chol: 290,
        fbs: 1,
        restecg: 2,
        thalach: 110,
        exang: 1,
        oldpeak: 2.6,
        slope: 2,
        ca: 2,
        thal: 7
      });
    } else {
      setFormData({
        age: 42,
        sex: 0,
        cp: 2, // Atypical
        trestbps: 120,
        chol: 195,
        fbs: 0,
        restecg: 0,
        thalach: 175,
        exang: 0,
        oldpeak: 0.2,
        slope: 1,
        ca: 0,
        thal: 3
      });
    }
    setResult(null);
  };

  return (
    <div style={{ maxWidth: 880, margin: '0 auto' }}>
      {/* Educational Notice Banner */}
      <div style={{
        background: 'rgba(239, 68, 68, 0.08)',
        border: '1px solid rgba(239, 68, 68, 0.25)',
        borderRadius: 'var(--radius-lg)',
        padding: '16px 20px',
        display: 'flex',
        alignItems: 'center',
        gap: 14,
        marginBottom: 24,
        color: '#fca5a5'
      }}>
        <ShieldAlert size={24} style={{ flexShrink: 0 }} />
        <div style={{ fontSize: '0.82rem', lineHeight: 1.5 }}>
          <strong>NON-CLINICAL EDUCATIONAL DISCLAIMER:</strong> This tool is an academic demonstration of Machine Learning inference.
          Predictions generated by this model are <strong>NOT medical diagnoses</strong> and must never replace qualified clinical evaluation by licensed physicians.
        </div>
      </div>

      <div className="card">
        <div className="card-header">
          <div className="card-title-group">
            <h3>Individual Clinical Risk Predictor</h3>
            <p>Enter patient physiological telemetry to evaluate model probability score</p>
          </div>
          <div style={{ display: 'flex', gap: 8 }}>
            <button className="btn-secondary" onClick={() => loadPreset('low')}>
              <span>Preset: Lower Risk</span>
            </button>
            <button className="btn-secondary" onClick={() => loadPreset('high')}>
              <span>Preset: Higher Risk</span>
            </button>
          </div>
        </div>

        <div className="card-body">
          <form onSubmit={handlePredict}>
            <div className="form-grid">
              {/* Age */}
              <div className="form-group">
                <label className="form-label">Age (Years)</label>
                <input
                  type="number"
                  name="age"
                  min="20"
                  max="95"
                  className="form-control"
                  value={formData.age}
                  onChange={handleChange}
                  required
                />
              </div>

              {/* Sex */}
              <div className="form-group">
                <label className="form-label">Biological Sex</label>
                <select name="sex" className="form-control" value={formData.sex} onChange={handleChange}>
                  <option value={1}>Male</option>
                  <option value={0}>Female</option>
                </select>
              </div>

              {/* Chest Pain */}
              <div className="form-group">
                <label className="form-label">Chest Pain Type</label>
                <select name="cp" className="form-control" value={formData.cp} onChange={handleChange}>
                  <option value={1}>Typical Angina (1)</option>
                  <option value={2}>Atypical Angina (2)</option>
                  <option value={3}>Non-Anginal Pain (3)</option>
                  <option value={4}>Asymptomatic (4)</option>
                </select>
              </div>

              {/* Resting Blood Pressure */}
              <div className="form-group">
                <label className="form-label">Resting BP (mm Hg)</label>
                <input
                  type="number"
                  name="trestbps"
                  min="80"
                  max="220"
                  className="form-control"
                  value={formData.trestbps}
                  onChange={handleChange}
                  required
                />
              </div>

              {/* Serum Cholesterol */}
              <div className="form-group">
                <label className="form-label">Serum Cholesterol (mg/dL)</label>
                <input
                  type="number"
                  name="chol"
                  min="100"
                  max="600"
                  className="form-control"
                  value={formData.chol}
                  onChange={handleChange}
                  required
                />
              </div>

              {/* Fasting Blood Sugar */}
              <div className="form-group">
                <label className="form-label">Fasting Blood Sugar &gt; 120</label>
                <select name="fbs" className="form-control" value={formData.fbs} onChange={handleChange}>
                  <option value={0}>False (&le; 120 mg/dL)</option>
                  <option value={1}>True (&gt; 120 mg/dL)</option>
                </select>
              </div>

              {/* Resting ECG */}
              <div className="form-group">
                <label className="form-label">Resting ECG Results</label>
                <select name="restecg" className="form-control" value={formData.restecg} onChange={handleChange}>
                  <option value={0}>Normal (0)</option>
                  <option value={1}>ST-T Wave Abnormality (1)</option>
                  <option value={2}>Left Ventricular Hypertrophy (2)</option>
                </select>
              </div>

              {/* Max Heart Rate */}
              <div className="form-group">
                <label className="form-label">Max Exercise HR (bpm)</label>
                <input
                  type="number"
                  name="thalach"
                  min="60"
                  max="220"
                  className="form-control"
                  value={formData.thalach}
                  onChange={handleChange}
                  required
                />
              </div>

              {/* Exercise Angina */}
              <div className="form-group">
                <label className="form-label">Exercise-Induced Angina</label>
                <select name="exang" className="form-control" value={formData.exang} onChange={handleChange}>
                  <option value={0}>No (0)</option>
                  <option value={1}>Yes (1)</option>
                </select>
              </div>

              {/* ST Depression */}
              <div className="form-group">
                <label className="form-label">ST Depression (oldpeak)</label>
                <input
                  type="number"
                  step="0.1"
                  name="oldpeak"
                  min="0.0"
                  max="7.0"
                  className="form-control"
                  value={formData.oldpeak}
                  onChange={handleChange}
                  required
                />
              </div>

              {/* Slope */}
              <div className="form-group">
                <label className="form-label">ST Segment Slope</label>
                <select name="slope" className="form-control" value={formData.slope} onChange={handleChange}>
                  <option value={1}>Upsloping (1)</option>
                  <option value={2}>Flat (2)</option>
                  <option value={3}>Downsloping (3)</option>
                </select>
              </div>

              {/* Major Vessels */}
              <div className="form-group">
                <label className="form-label">Major Vessels (ca: 0-3)</label>
                <input
                  type="number"
                  name="ca"
                  min="0"
                  max="4"
                  className="form-control"
                  value={formData.ca}
                  onChange={handleChange}
                  required
                />
              </div>

              {/* Thal */}
              <div className="form-group">
                <label className="form-label">Thallium Stress Result</label>
                <select name="thal" className="form-control" value={formData.thal} onChange={handleChange}>
                  <option value={3}>Normal (3)</option>
                  <option value={6}>Fixed Defect (6)</option>
                  <option value={7}>Reversible Defect (7)</option>
                </select>
              </div>
            </div>

            <div style={{ marginTop: 24 }}>
              <button
                type="submit"
                className="btn-primary"
                style={{ width: '100%', padding: '12px', justifyContent: 'center', fontSize: '0.95rem' }}
                disabled={loading}
              >
                <Play size={16} />
                <span>{loading ? 'Evaluating Model Inference...' : 'Predict Patient Cardiac Risk'}</span>
              </button>
            </div>
          </form>

          {errorMsg && (
            <div style={{ marginTop: 16, color: '#EF4444', fontSize: '0.85rem' }}>
              {errorMsg}
            </div>
          )}

          {/* Prediction Result Display */}
          {result && (
            <div className="prediction-result-banner">
              <span className="metric-label">Model Predicted Probability</span>
              <div style={{
                fontSize: '3rem',
                fontWeight: 800,
                color: result.prediction === 1 ? '#EF4444' : '#10B981',
                margin: '10px 0'
              }}>
                {result.probability_percent}%
              </div>
              <div style={{ fontSize: '1.25rem', fontWeight: 700, color: '#fff' }}>
                Classification: <span style={{ color: result.prediction === 1 ? '#EF4444' : '#10B981' }}>{result.prediction_label}</span>
              </div>
              <p style={{ fontSize: '0.85rem', color: 'var(--text-muted)', marginTop: 4 }}>
                Risk Stratification Tier: <strong>{result.risk_tier}</strong>
              </p>
              <div style={{
                fontSize: '0.75rem',
                color: 'var(--text-dim)',
                marginTop: 14,
                borderTop: '1px solid var(--border-subtle)',
                paddingTop: 10
              }}>
                {result.disclaimer}
              </div>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
